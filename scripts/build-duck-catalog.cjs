// Export public navigation targets from the reviewed classrooms. No student data or answers.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const repo=path.resolve(__dirname,'..'),web=path.join(repo,'app/src/main/assets/web/app-design');
const context=vm.createContext({window:{}});
for(const name of ['curriculum.js','english-vocabulary.js','english-lessons.js'])vm.runInContext(fs.readFileSync(path.join(web,name),'utf8'),context,{filename:name});
const data={math:require(path.join(web,'math-data.js')),physics:require(path.join(web,'physics-data.js'))};
const routes=[],numerals=['零','一','二','三','四','五','六','七','八','九','十','十一'];
const aliases={
  'tri-lines':['中线','高线','三角形的高'], 'tri-angles':['三角形内角和','三角形外角'],
  'factor-difference':['平方差公式'], 'factor-perfect':['完全平方公式'],
  'phy-reflection':['光的反射','光反射','反射定律'],
};
for(const [subject,course] of Object.entries(context.window.GrowingCurriculum))for(const [term,book] of Object.entries(course.terms)){
  if(!book.verified)continue;
  for(const unit of book.units){
    if(!/^(?:math|physics|english)-course\.html\?/.test(unit.entry))continue; // The two legacy classrooms do not host the companion yet.
    const prefix={subject,unitId:unit.id,unitTitle:unit.title};
    const items=subject==='english'?[
      ...(context.window.GrowingEnglishLessons[unit.number]||[]).map(l=>({topicId:l.id,title:l.title,kind:'lesson'})),
      ...(context.window.GrowingEnglishVocabulary[unit.number]||[]).map(w=>({topicId:w.id,title:w.word,kind:'word'})),
    ]:data[subject].chapters.find(c=>c.id===unit.id).nodes.map(n=>({topicId:n.id,title:n.title,kind:'node'}));
    const target=item=>{
      const params=new URLSearchParams(subject==='english'?{unit:unit.id,[item.kind==='word'?'word':'lesson']:item.topicId}:{chapter:unit.id,node:item.topicId});
      return {courseId:(subject==='english'?'':subject+':')+unit.id+':'+item.topicId,href:(subject==='english'?'english':subject)+'-course.html?'+params};
    };
    const first=items.find(n=>n.title===unit.title+'的概念'||n.title===unit.title)||items.find(n=>n.kind==='word')||items[0];
    routes.push({...prefix,id:'unit:'+unit.id,title:unit.title,kind:'unit',...target(first),aliases:subject==='english'?['英语第'+unit.number+'单元','英语第'+numerals[unit.number]+'单元','Unit '+unit.number]:[course.name+'第'+unit.number+'章',course.name+'第'+numerals[unit.number]+'章',course.name+(term==='upper'?'上册':'下册')+'第'+numerals[unit.number]+'章']});
    for(const item of items)routes.push({...prefix,id:target(item).courseId,title:item.title,topicId:item.topicId,kind:item.kind,...target(item),aliases:[...(aliases[item.topicId]||[]),...(item.kind==='lesson'?item.title.split(/[：:]/).slice(1):[])]});
  }
}
if(routes.length<100||!routes.some(r=>r.id==='math:math-8b-09:factor-concept'))throw Error('Reviewed navigation catalogue is incomplete.');
const output='// Generated by growing/scripts/build-duck-catalog.cjs from reviewed course assets.\nexport const destinations='+JSON.stringify(routes)+';\n';
for(const folder of [path.resolve(repo,'../app-design/companion-duck'),path.join(web,'companion-duck'),path.join(repo,'cloudflare/public/learn/app-design/companion-duck')]){
  fs.mkdirSync(folder,{recursive:true});const file=path.join(folder,'course-catalog.js');
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==output)fs.writeFileSync(file,output);
}
console.log('Exported '+routes.length+' public duck navigation targets.');
