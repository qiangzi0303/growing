const fs=require('node:fs'),path=require('node:path');
const dir=path.resolve(__dirname,'../app/src/main/assets/web/app-design');
const data=JSON.parse(fs.readFileSync(path.join(dir,'math-week13/paper.json'),'utf8'));
const math=require(path.join(dir,'math-data.js'));
const katex=require('../cloudflare/node_modules/katex');
const drawing=require('../platform-web/question-drawing.js');
if(data.questions.length!==34)throw Error('Expected 34 questions');
for(const [i,q] of data.questions.entries()){
 if(q.number!==i+1||!math.chapters.find(c=>c.id===q.practice.unitId)?.nodes.some(n=>n.id===q.practice.nodeId))throw Error('Invalid question mapping '+q.number);
 for(const s of [q.body,...q.options,...q.parts,q.answer,q.explanation])for(const match of s.matchAll(/\$([^$]+)\$/g))katex.renderToString(match[1],{throwOnError:true});
 if(q.drawing&&!drawing.normalize(q.drawing))throw Error('Invalid drawing '+q.number);
 for(const f of [...q.figures,...q.originals])if(!fs.existsSync(path.join(dir,f)))throw Error('Missing asset '+f);
}
fs.writeFileSync(path.join(dir,'math-week13-data.js'),'/* Generated by scripts/build-week13.cjs. */\nwindow.GrowingWeek13Data='+JSON.stringify(data)+';\n');
console.log(JSON.stringify({questions:data.questions.length,wrong:data.questions.filter(q=>q.originalReview.wrong).map(q=>q.number),review:data.questions.filter(q=>q.originalReview.verdict==='review').map(q=>q.number),units:[...new Set(data.questions.map(q=>q.practice.unitId))]}));
