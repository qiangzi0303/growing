import { expect, it, vi } from 'vitest';
import { mount, flushPromises } from '@vue/test-utils';
import { createPinia, setActivePinia } from 'pinia';
const logout = vi.hoisted(() => vi.fn());
vi.mock('../src/service/api/auth', () => ({ fetchLogout: logout, fetchLogin: vi.fn(), fetchGetUserInfo: vi.fn() }));
vi.mock('../src/service/request', () => ({ api: { cancelAll: vi.fn() } }));
vi.mock('../src/locales', () => ({ $t: (key: string) => key }));
vi.mock('../src/hooks/common/router', () => ({ useRouterPush: () => ({ toLogin: vi.fn(), routerPushByKey: vi.fn() }) }));
vi.mock('../src/hooks/common/icon', () => ({ useSvgIcon: () => ({ SvgIconVNode: () => () => null }) }));
import UserAvatar from '../src/layouts/modules/global-header/components/user-avatar.vue';
import { useAuthStore } from '../src/store/modules/auth';
it('shows failed logout and lets the actual header retry successfully', async () => {
  setActivePinia(createPinia());
  const store = useAuthStore();
  store.profile = { id: 'p', username: 'p', displayName: 'p', role: 'Parent', roleSelectionRequired: false };
  logout.mockResolvedValueOnce({ data: null, error: new Error('offline') }).mockResolvedValueOnce({ data: null, error: null });
  let confirm!: () => Promise<unknown>;
  window.$dialog = { info: vi.fn(options => { confirm = options.onPositiveClick; }) } as never;
  const wrapper = mount(UserAvatar, { global: { mocks: { $t: (key: string) => key }, stubs: { NDropdown: { template: '<div @click="$emit(\'select\', \'logout\')"><slot /></div>' }, NButton: { template: '<button><slot /></button>' }, ButtonIcon: { template: '<span><slot /></span>' }, SvgIcon: true } } });
  await wrapper.find('div').trigger('click');
  await confirm();
  await flushPromises();
  expect(store.isLogin).toBe(false);
  expect(wrapper.text()).toContain('退出未完成');
  await wrapper.findAll('button').find(button => button.text().includes('重试退出'))!.trigger('click');
  await flushPromises();
  expect(logout).toHaveBeenCalledTimes(2);
  expect(wrapper.text()).not.toContain('退出未完成');
  wrapper.unmount();
});
